    <h2>ESTRUCTURAS REPETITIVAS</h2><br>
    </h2><br> <p> Las estructuras repetitivas permiten ejecutar un bloque de código varias veces mientras se cumpla una condición. </p> <br>

    <h3>FOR</h3><br>
     <p> Se usa cuando conocemos la cantidad exacta de repeticiones. <br>
     for (int i = 0; i < 10; i++) {<br>
     System.out.println(i);<br>
    }<br> </p>

    <h3>WHILE</h3> <br>
    <p> Se ejecuta mientras la condición sea verdadera. <br>
    while (numero > 0) {<br>
    numero--;<br>
    }<br></p> 

    <h3>DO WHILE</h3><br>
    <p> A diferencia de <i>while</i>, aquí el bloque se ejecuta al menos una vez. <br>
    do {<br>
    opcion = leerOpcion();<br>
} while (opcion != 0);<br></p>

<h2>POO (ATRIBUTOS Y METODOS )</h2><br>

<h3>ATRIBUTOS</h3>
<p> Los atributos representan las características o estado de un objeto. Se declaran dentro de una clase. <br>
Son variables dentro de una clase. Representan el estado de un objeto.<br>
class Persona {<br>
    String nombre;<br>
    int edad;<br>
}<br></p>

<h3>METODOS</h3><br>
<p>Los métodos representan las acciones o comportamientos que un objeto puede realizar
Son las acciones o comportamientos de los objetos.<br>
void saludar() {<br>
    System.out.println("Hola");<br>
}<br></p>

<h2>HERENCIA</h2><br>
<p>La herencia permite que una clase hija herede atributos y métodos de una clase padre. Es uno de los pilares fundamentales de la Programación Orientada a Objetos porque promueve la reutilización y evita duplicar código.<br>
    Es uno de los pilares fundamentales de la Programación Orientada a Objetos en Java.<br>
Consiste en que una clase (llamada clase hija, subclase o derivada) puede heredar atributos y métodos de otra clase (llamada clase padre, superclase o base).<br>
Esto permite reutilizar código, organizar mejor los programas y representar relaciones del mundo real.</p><br>
