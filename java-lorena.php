<h2>HERENCIA</h2><br>
<p>La herencia es uno de los pilares fundamentales de la Programación Orientada a Objetos en Java.
Consiste en que una clase (llamada clase hija, subclase o derivada) puede heredar atributos y métodos de otra clase (llamada clase padre, superclase o base).

Esto permite reutilizar código, organizar mejor los programas y representar relaciones del mundo real.</p><br>



